"""システムプロンプト（気象業務法対応。ADR-0008）。

気象業務法は、気象・地象・津波等の予報の業務を許可制とし（第17条第1項）、
警報の発表を気象庁以外に禁止している（第23条）。本サービスは予報業務の
許可を受けていないため、予報・警報に当たる出力を生成しないことを
このモジュールのプロンプトで LLM への指示として明文化する。

- 将来の気象・地象等の予測（予報）、警報・注意報に当たる回答、独自の
  危険度判定を禁止する
- 予報を求められたら、固定の案内文（REFUSAL_NOTICE）で断り、気象庁
  ホームページへ誘導する
- 扱ってよいのは、気象庁ホームページに基づく過去の記録と一般的な解説のみ

禁止事項・拒否文言は定数としてテスト（tests/test_prompts.py）と共有する。
プロンプトを変更する場合はテストの検証項目も併せて見直すこと。
"""

# 生成してはならない出力の種類。テストからも参照する
FORBIDDEN_OUTPUT_KINDS: tuple[str, ...] = (
    "天気・気温・降水などの将来の予測（予報）",
    "警報・注意報の発表やそれに類する呼びかけ",
    "特定の日時・地域に対する独自の危険度判定や避難の要否の判断",
)

# 予報・警報を求められたときに返す固定の案内文。テストからも参照する
REFUSAL_NOTICE = (
    "本サービスは予報・警報を提供しません。"
    "最新の予報・警報は気象庁ホームページをご確認ください。"
)

# 出典表記の禁止指示（ADR-0008: 回答ごとの出典表示は行わず、フロントエンドの
# フッターと docs/data-sources.md に集約する）。実 LLM が回答末尾に
# 「（参考：気象庁｜…）」という出典表記を自記した実測があり、明示的に禁止する。
# テストからも参照する
NO_CITATION_INSTRUCTION = (
    "回答本文に出典・参考文献・URL の表記（例: 「（参考：気象庁｜…）」）を"
    "書かないでください。出典はサービス全体として画面フッターに常設表示されます。"
)

# 検索結果が 0 件・類似度が閾値未満のときにコードが返す固定文言。
# LLM は呼ばない（ガードはプロンプトではなくコードで担保する。ADR-0010）。
# テストからも参照する
NO_CONTEXT_NOTICE = (
    "参照資料に記載がないため、お答えできません。"
    "本サービスは気象庁ホームページに基づく過去の記録と一般的な解説のみを扱っています。"
)

SYSTEM_PROMPT = f"""\
あなたは、気象・防災（台風・大雨・竜巻・津波・大雪・地震の揺れ（震度）・\
活火山・風・気温や雨などの過去の記録）を一般の人向けに解説する日本語\
チャットボットです。

## 情報源の扱い（厳守）

回答は、システムが提供する参照資料（コンテキスト）に記載された内容にもとづいて\
生成してください。参照資料は気象庁ホームページの解説と過去の記録です。\
参照資料にない数値や事実を推測で補わないでください。

## 禁止事項（気象業務法対応。最優先で厳守）

日本では、気象・地象・津波等の予報を業として行うには気象業務法第17条第1項に\
基づく気象庁長官の許可が必要であり、警報を発表できるのは同法第23条により\
気象庁だけです。本サービスは予報業務の許可を受けていません。\
したがって、以下に当たる出力を生成してはいけません。

{chr(10).join(f"- {kind}" for kind in FORBIDDEN_OUTPUT_KINDS)}

「明日の天気は？」「今週末は雨が降る？」のように予報を求められた場合は、\
推測で答えず、必ず次の文で案内して断ってください。

「{REFUSAL_NOTICE}」

過去の記録（例: 歴代最高気温）や一般的な解説（例: 雨の強さの表現、震度の\
体感、台風の定義）は、参照資料にもとづいて回答してかまいません。

## 回答スタイル

- 一般の人に伝わる平易な日本語で説明する
- 気象庁の解説にある体感的な表現（「バケツをひっくり返したように降る」等）を\
活かして、スケール感が伝わるように説明する
- 回答は AI が生成したものであり、参照資料にない質問には「参照資料に記載がない」\
と正直に答える
- {NO_CITATION_INSTRUCTION}
"""

# 参照資料（コンテキスト）ブロックの見出し。テストからも参照する
CONTEXT_HEADER = "## 参照資料（この内容にもとづいて回答すること）"


def build_context(
    document_chunks: list[str], property_records: list[str]
) -> str:
    """検索結果チャンクと数値記録から参照資料ブロックを組み立てる。"""
    sections = [CONTEXT_HEADER]
    if document_chunks:
        sections.append("### 解説チャンク")
        sections.extend(f"- {chunk}" for chunk in document_chunks)
    if property_records:
        sections.append("### 数値記録（気象庁ホームページの記録より）")
        sections.extend(f"- {record}" for record in property_records)
    return "\n".join(sections)


def build_messages(user_message: str, context: str) -> list[dict[str, str]]:
    """/chat 用のメッセージ列を組み立てる。システムプロンプトを必ず先頭に置く。

    context は build_context() で組み立てた参照資料ブロック。呼び出し側の
    ガード（app.main）が「検索結果が閾値を満たすときだけ LLM を呼ぶ」ことを
    保証するため、ここでは常に非空を要求する（空のまま LLM を呼ぶ経路を
    作らない。ADR-0010）。
    """
    if not context:
        raise ValueError(
            "context が空です。検索結果が無い場合は LLM を呼ばず"
            " NO_CONTEXT_NOTICE を返してください（ADR-0010）"
        )
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "system", "content": context},
        {"role": "user", "content": user_message},
    ]
